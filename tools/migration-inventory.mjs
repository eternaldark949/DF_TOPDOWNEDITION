// Every classic script in the playable build, and where it goes on the new engine.
//   node tools/migration-inventory.mjs           rewrite docs/migration/README.md from inventory.json
//   node tools/migration-inventory.mjs --check   fail if a build script has no inventory row (or a row
//                                                names a script the build no longer has), or the page is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const root = new URL('../', import.meta.url), read = p => readFileSync(new URL(p, root), 'utf8');
const build = read('tools/build.mjs'), start = build.indexOf('const SCRIPTS = [');
const scripts = [...build.slice(start, build.indexOf('];', start)).matchAll(/^\s*'([^']+)'/gm)].map(m => m[1]);
const rows = JSON.parse(read('docs/migration/inventory.json'));

const STATUS = {
    replaced: 'A Basement/Directory replacement exists. Switch the remaining callers, then delete.',
    partly: 'Part of it has a new home; the rest still needs porting.',
    to_build: 'No new home yet. The Basement or Directory service must be built first.',
    art: 'Drawing code. Convert to appearance producers that submit render packets.',
    game_logic: 'Game rules or UI that stay, but must run on the new runtime and native entities.',
    glue: 'Classic engine wiring. Goes away when the new runtime boots the game.',
    data: 'Data. Stays; native code reads the same files.',
    native: 'Already the new engine.'
};
const lines = file => file.startsWith('@') || file.endsWith('.json') || !existsSync(new URL(`src/${file}`, root)) ? 0 : read(`src/${file}`).split('\n').length;

const problems = [];
const known = new Set(rows.map(r => r.file));
for (const file of scripts) if (!known.has(file)) problems.push(`no inventory row for build script ${file}`);
for (const r of rows) {
    if (!scripts.includes(r.file)) problems.push(`inventory row for ${r.file}, which the build no longer includes (remove the row once it is deleted)`);
    if (!STATUS[r.status]) problems.push(`${r.file}: unknown status ${r.status}`);
}

const total = rows.reduce((n, r) => n + lines(r.file), 0), by = key => {
    const out = new Map();
    for (const r of rows) { const e = out.get(r[key]) ?? { files: 0, lines: 0 }; e.files++; e.lines += lines(r.file); out.set(r[key], e); }
    return [...out].sort((a, b) => b[1].lines - a[1].lines);
};
const page = `# Classic-to-Basement migration inventory

Generated by \`node tools/migration-inventory.mjs\` from [inventory.json](inventory.json). Every script the classic build links has exactly one row; \`--check\` (run in CI) fails when a new classic script appears without one, or a deleted one keeps its row. Edit the JSON, then regenerate.

The classic build links **${rows.length} scripts, ${total.toLocaleString('en-US')} lines**. The physics-specific retirement gate is \`node tools/audit-physics-ownership.mjs\`; this page covers everything else too.

## Services the new engine still lacks

These have no Basement or Directory home yet, so the scripts that need them cannot move until they exist:

1. **Audio.** \`basement/sound-system.js\`, \`sound-kit.js\`, \`directory/game-sound.js\`: channels, reverb, music by room. The room graph's \`exposure\` can drive through-door attenuation.
2. **UI and HUD.** \`ui/ui-system.js\`, \`basement/ui-kit.js\` and the menus, phone, inventory and dialogue screens. They need a Basement UI layer that draws through the render system and reads controls.
3. **Lighting.** \`engine/lighting.js\`, \`daylight.js\`, \`reflections.js\`, and the classic RoomSystem's veil and darkness. Light shapes are in the grid already; there is no lighting pass in the renderer.
4. **Game-wide saves.** \`engine/save-load.js\`. Physics snapshots exist per world; a runtime-wide save envelope does not.
5. **Weather, decals and screen effects.** \`world/weather.js\`, \`particles-decals.js\`, \`engine/combat-effects.js\`. Particles exist; decals and weather layers do not.
6. **City generation.** \`world/city-layout.js\` fills blocks at random on load. It must become seeded generation into exterior map data for the map system.
7. **A native map host for every map.** \`engine/apartment-level.js\` hosts one map. It needs to become the host for any map whose layout file says \`"host": "native"\`.
8. **Timers.** \`basement/timer-kit.js\`: gameplay timers need a runtime-owned service.

## By status

| Status | Files | Lines | Meaning |
|---|---:|---:|---|
${Object.keys(STATUS).map(s => { const e = by('status').find(([k]) => k === s)?.[1] ?? { files: 0, lines: 0 }; return `| \`${s}\` | ${e.files} | ${e.lines.toLocaleString('en-US')} | ${STATUS[s]} |`; }).join('\n')}

## By area

| Area | Files | Lines |
|---|---:|---:|
${by('area').map(([area, e]) => `| ${area} | ${e.files} | ${e.lines.toLocaleString('en-US')} |`).join('\n')}

## Every script

| Script | Lines | Area | Status | Goes to | Notes |
|---|---:|---|---|---|---|
${rows.map(r => `| \`${r.file}\` | ${lines(r.file)} | ${r.area} | \`${r.status}\` | ${r.target} | ${r.note} |`).join('\n')}
`;

if (process.argv.includes('--check')) {
    if (read('docs/migration/README.md') !== page) problems.push('docs/migration/README.md is stale: run node tools/migration-inventory.mjs');
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    console.log(`Migration inventory covers all ${scripts.length} classic scripts.`);
} else {
    if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
    writeFileSync(new URL('docs/migration/README.md', root), page);
    console.log(`Wrote docs/migration/README.md (${rows.length} scripts).`);
}
